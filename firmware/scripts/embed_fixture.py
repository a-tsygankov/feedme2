"""Embed fixtures/device-state.sample.json as a C string for the simulator.

The simulator env swaps WifiNetwork for FakeNetwork, which serves the
cross-tier sample state so Wokwi scenarios see the same cats (Mochi, Luna)
the webapp and backend tests do. Generating the header at build time keeps
`fixtures/` the single source of truth; the output is gitignored.
"""
from __future__ import annotations
import json
from pathlib import Path

Import("env")  # noqa: F821 — provided by PlatformIO

project_dir = Path(env["PROJECT_DIR"])  # noqa: F821
src = project_dir.parent / "fixtures" / "device-state.sample.json"
out = project_dir / "src" / "adapters" / "FakeState.h"

# Re-serialise compactly so the header does not carry the fixture's whitespace;
# json.loads first so a broken fixture fails the build here, not at runtime.
data = json.dumps(json.loads(src.read_text(encoding="utf-8")), separators=(",", ":"))
body = data.replace("\\", "\\\\").replace('"', '\\"')
header = (
    "// generated by scripts/embed_fixture.py from fixtures/device-state.sample.json - do not edit\n"
    "#pragma once\n"
    "namespace feedme2::adapters {\n"
    'inline const char* kFakeStateJson = "' + body + '";\n'
    "}  // namespace feedme2::adapters\n"
)
# Only touch the file when the content changed, so an unchanged fixture does
# not force FakeNetwork.cpp to recompile on every build.
if not out.exists() or out.read_text(encoding="utf-8") != header:
    out.write_text(header, encoding="utf-8")
    print(f"[embed_fixture] wrote {out}")
