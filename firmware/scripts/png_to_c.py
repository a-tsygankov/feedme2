#!/usr/bin/env python3
"""Wrap a PNG file in a C source file holding an LVGL 9.0 lv_image_dsc_t.

usage: png_to_c.py <in.png> <symbol> <out.c>

The descriptor is LV_COLOR_FORMAT_RAW: LVGL's lodepng decoder inflates the PNG
at draw time, so flash holds the compressed bytes only. Output is a pure
function of the input bytes (no timestamps) so regenerating is a no-op in git.
"""
from __future__ import annotations
import struct
import sys
from pathlib import Path

PNG_MAGIC = b"\x89PNG\r\n\x1a\n"


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    src, symbol, out = Path(argv[1]), argv[2], Path(argv[3])
    data = src.read_bytes()
    if not data.startswith(PNG_MAGIC):
        raise SystemExit(f"{src}: not a PNG")
    # IHDR width/height are big-endian at fixed offsets 16 and 20.
    w, h = struct.unpack(">II", data[16:24])
    rows = []
    # Decimal without spaces: ~40% smaller source than "0x89, " (spec D2 caps the
    # generated sources at 250 KB; the compiled bytes are identical either way).
    for i in range(0, len(data), 32):
        rows.append(",".join(str(b) for b in data[i:i + 32]) + ",")
    text = (
        "// generated by assets/cats/render.py - do not edit\n"
        "#include <lvgl.h>\n"
        # aligned(4): the lodepng decoder casts data to uint32_t* to read IHDR
        # when header.w/h are 0; keep that safe on Xtensa, which faults on
        # unaligned 32-bit loads.
        f"static const uint8_t {symbol}_map[] __attribute__((aligned(4))) = {{\n"
        + "\n".join(rows)
        + "\n};\n"
        f"const lv_image_dsc_t {symbol} = {{\n"
        f"    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RAW, .flags = 0, .w = {w}, .h = {h}, .stride = 0 }},\n"
        f"    .data_size = sizeof({symbol}_map), .data = {symbol}_map,\n"
        "};\n"
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    # newline="" keeps LF on Windows.
    with open(out, "w", encoding="ascii", newline="") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
